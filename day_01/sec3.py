# Index a string at position 0, 1, -1

str = 'SHADAB'
print(str[0])
print(str[1])
print(str[-1])

# Slice a string: first 5 chars, last 3 chars, middle section

print(str[:5])
print(str[3:])

print(str[2:4])

# Convert string to uppercase, lowercase

s = 'shadab'
print(s.upper())
print(str.lower())

# Split a string by spaces
st = 'shadab danish'
print(st.split())

# Join a list of strings with a separator
print(''.join(['shadab',' ','danish']))